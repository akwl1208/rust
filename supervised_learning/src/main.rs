/// 평균제곱오차: MSE = (1/N) sum (w*x + b - y)^2
fn mse(data: &[(f64, f64)], w: f64, b: f64) -> f64 {
    let n = data.len() as f64;
    data.iter()
        .map(|(x, y)| {
            let pred = w * x + b;
            (pred - y).powi(2)
        })
        .sum::<f64>()
        / n
}