// ================================================================
// 개념 1: 머신러닝이란 무엇인가
// ================================================================
//
// 전통적 프로그래밍과 머신러닝의 차이가 핵심입니다.
//
//   [전통적 프로그래밍]
//      규칙(코드) + 입력  ->  출력
//      사람이 "어떻게 풀지"를 직접 다 적는다.
//      예: if 온도 > 28 { "더움" } else { "안 더움" }
//
//   [머신러닝]
//      입력 + 출력(정답)  ->  규칙(모델)
//      "정답이 이거다"라는 예시만 잔뜩 주면,
//      기계가 입력->출력을 잇는 규칙을 스스로 찾아낸다.
//
// 즉 머신러닝 = "데이터로부터 패턴(규칙)을 학습하는 알고리즘".
// 사람이 규칙을 짜는 게 아니라, 데이터가 규칙을 만든다.
 
fn concept1_what_is_ml() {
    println!("-- 개념 1: 머신러닝이란? --\n");
 
    println!("전통적 프로그래밍:  규칙 + 입력 -> 출력");
    println!("                    (사람이 규칙을 직접 작성)");
    println!();
    println!("머신러닝:           입력 + 정답 -> 규칙(모델)");
    println!("                    (기계가 규칙을 스스로 발견)");
    println!();
    println!("핵심: '어떻게 푸는지'를 사람이 안 적고,");
    println!("      '정답 예시'만 잔뜩 보여주면 기계가 패턴을 찾는다.\n");
}
 
 
// ================================================================
// 개념 2: 지도학습 vs 비지도학습
// ================================================================
//
// [지도학습 Supervised Learning]
//   - 입력 x 와 정답 y 가 '쌍'으로 주어진다.   (x, y)
//   - 모델이 x->y 관계를 배우게 한다.
//   - 두 종류:
//       . 분류(Classification): 정답이 '카테고리'  (개/고양이, 스팸/정상)
//       . 회귀(Regression):     정답이 '숫자'      (집값, 온도, 키)
//   - 예: 사진(x) -> "고양이"(y),  평수(x) -> 집값(y)
//
// [비지도학습 Unsupervised Learning]
//   - 정답 y 가 없다. 입력 x 만 있다.
//   - 데이터 안의 '숨은 구조'를 스스로 발견한다.
//   - 예: 군집화(비슷한 고객끼리 묶기), 차원 축소
//
// LLM 파인튜닝은 '지도학습'입니다:
//   instruction(x) -> response(y) 라는 쌍으로 가중치를 조정.
 
fn concept2_supervised_vs_unsupervised() {
    println!("-- 개념 2: 지도학습 vs 비지도학습 --\n");
 
    println!("[지도학습] 입력 + 정답 쌍 (x, y) 으로 학습");
    println!("  . 분류: 정답이 카테고리 -> 예) 사진 -> '고양이'");
    println!("  . 회귀: 정답이 숫자     -> 예) 평수 -> 집값(3억)");
    println!();
    println!("[비지도학습] 정답 없이 입력 x 만 -> 숨은 구조 발견");
    println!("  . 예) 비슷한 고객끼리 자동으로 그룹화 (군집화)");
    println!();
    println!("-> LLM 파인튜닝 = 지도학습");
    println!("   instruction(입력) -> response(정답) 쌍으로 학습\n");
}
 
 
// ================================================================
// 개념 3: 가중치(Weight)와 편향(Bias)
// ================================================================
//
// 모델은 결국 '입력을 출력으로 바꾸는 함수'입니다.
// 가장 단순한 형태가 직선:
//
//      y = w*x + b
//
//   w (weight, 가중치): 직선의 기울기. "입력이 출력에 얼마나 영향을 주나"
//   b (bias, 편향):     직선의 y절편.  "기본적으로 깔고 가는 값"
//
// 학습이란 = 데이터에 가장 잘 맞는 w 와 b 를 찾는 것.
// w, b 를 '학습되는 파라미터(parameter)'라고 부른다.
//
// LLM은 이 파라미터가 수십억~수천억 개. 원리는 똑같다.
 
fn concept3_weight_and_bias() {
    println!("-- 개념 3: 가중치(w)와 편향(b) --\n");
 
    println!("모델(직선): y = w*x + b");
    println!("  w (가중치): 기울기 - 입력의 영향력");
    println!("  b (편향):   y절편 - 기본값");
    println!();
 
    let x = 3.0;
    println!("같은 입력 x={x} 일 때 w,b 에 따른 출력:");
    for (w, b) in [(1.0, 0.0), (2.0, 0.0), (2.0, 1.0), (0.5, 5.0)] {
        let y = w * x + b;
        println!("  w={w}, b={b}  ->  y = {w}*{x} + {b} = {y}");
    }
    println!();
    println!("학습 = 데이터에 가장 잘 맞는 (w, b) 찾기");
    println!("LLM은 이런 파라미터가 수십억 개일 뿐, 원리는 동일\n");
}
 
 
// ================================================================
// 개념 4: 손실(Loss) - 가중치를 바꾸며 관찰
// ================================================================
//
// "잘 맞는다"를 어떻게 숫자로 잴까? -> 손실 함수(Loss).
//
// 회귀에서 가장 흔한 손실: 평균제곱오차 (MSE, Mean Squared Error)
//
//      MSE = (1/N) * sum (예측값 - 정답)^2
//
//   . 예측이 정답과 똑같으면 -> 오차 0 -> MSE 0 (완벽)
//   . 예측이 정답에서 멀수록 -> 제곱이라 손실이 급격히 커짐
//   . 제곱하는 이유: 부호 없애기 + 큰 오차에 더 큰 벌점
//
// 이번 실습 데이터의 '진짜 관계'는 y = 2x + 1 입니다.
// 여러 (w, b) 를 넣어보며 손실이 어떻게 변하는지 봅시다.
 
fn concept4_loss_landscape() {
    println!("-- 개념 4: 손실(MSE) - 가중치를 바꿔보며 관찰 --\n");
 
    let data = sample_data();
    println!("데이터 (진짜 관계: y = 2x + 1):");
    for (x, y) in &data {
        println!("  x={x}, y={y}");
    }
    println!();
 
    println!("MSE = (1/N) sum (예측 - 정답)^2   (낮을수록 좋음)\n");
    println!("{:>6} {:>6} {:>12}", "w", "b", "MSE");
    println!("{}", "-".repeat(26));
 
    let candidates = [
        (0.0, 0.0),
        (1.0, 0.0),
        (2.0, 0.0),
        (2.0, 1.0),  // <- 진짜 정답
        (3.0, 1.0),
        (2.0, 2.0),
    ];
    for (w, b) in candidates {
        let loss = mse(&data, w, b);
        let marker = if loss < 1e-9 { "  <- 완벽! (정답)" } else { "" };
        println!("{w:>6.1} {b:>6.1} {loss:>12.4}{marker}");
    }
    println!();
    println!("관찰: (w=2, b=1) 에서 MSE=0. 진짜 관계를 정확히 맞춤.");
    println!("      정답에서 멀어질수록 손실이 빠르게 커진다.");
    println!("      -> 학습이란 이 MSE를 가장 작게 만드는 (w,b) 찾기\n");
}
 
 
// ================================================================
// 개념 5: 경사하강법 - 손실을 자동으로 줄이기
// ================================================================
//
// 위에서는 사람이 (w,b) 를 손으로 넣어봤습니다. 비효율적이죠.
// 기계는 '기울기(gradient)'를 이용해 자동으로 정답을 찾아갑니다.
//
//   1. 손실 L 을 w, b 로 각각 편미분 -> 기울기 (dL/dw, dL/db)
//   2. 기울기는 'L이 가장 빨리 커지는 방향' -> 그 반대로 가면 L이 준다
//   3. 업데이트:  w <- w - (학습률 * dL/dw)
//                 b <- b - (학습률 * dL/db)
//   4. 1~3 을 반복하면 손실이 점점 줄어 최저점에 도달
//
// 이게 '경사하강법(Gradient Descent)'. 모든 딥러닝 학습의 엔진입니다.
// (Day 36-37 에서 만든 수치 미분이 바로 이 기울기를 구하는 도구)
//
// MSE = (1/N)sum(wx+b - y)^2 의 기울기 (미분으로 유도):
//   dL/dw = (1/N) sum 2(wx+b - y)*x
//   dL/db = (1/N) sum 2(wx+b - y)
 
fn concept5_gradient_descent() {
    println!("-- 개념 5: 경사하강법 - 자동 학습 --\n");
 
    let data = sample_data();
    let mut w = 0.0; // 아무것도 모르는 상태에서 시작
    let mut b = 0.0;
    let lr = 0.01;   // 학습률 (한 걸음의 크기)
    let n = data.len() as f64;
 
    println!("시작: w=0, b=0 (백지 상태),  학습률=0.01");
    println!("목표: 데이터의 진짜 관계 y = 2x + 1 찾기\n");
 
    println!("{:>8} {:>10} {:>10} {:>12}", "step", "w", "b", "MSE");
    println!("{}", "-".repeat(44));
 
    let report_at = [1, 10, 100, 500, 1000, 2000];
    for step in 1..=2000 {
        let mut dw = 0.0;
        let mut db = 0.0;
        for (x, y) in &data {
            let pred = w * x + b;
            let err = pred - y;
            dw += 2.0 * err * x;
            db += 2.0 * err;
        }
        dw /= n;
        db /= n;
 
        w -= lr * dw;
        b -= lr * db;
 
        if report_at.contains(&step) {
            println!("{step:>8} {w:>10.4} {b:>10.4} {:>12.6}", mse(&data, w, b));
        }
    }
    println!();
    println!("결과: w~2.00, b~1.00 - 진짜 관계 y=2x+1 을 스스로 찾음!");
    println!("-> 사람이 정답을 안 알려줘도, 손실을 줄이는 방향만 따라가면");
    println!("   기계가 알아서 올바른 가중치에 도달한다. 이게 '학습'.\n");
}
 
 
// ================================================================
// 개념 6: 과적합(Overfitting)과 일반화(Generalization)
// ================================================================
//
// 학습의 진짜 목표는 '훈련 데이터를 외우는 것'이 아니라
// '본 적 없는 새 데이터에도 잘 맞추는 것' = 일반화(Generalization).
//
// [과적합 Overfitting]
//   훈련 데이터에는 완벽(심지어 노이즈까지 외움)하지만,
//   새로운 데이터에는 형편없는 상태.
//   "기출문제만 통째로 외운 학생"과 같다.
//   -> 시험에 똑같은 문제 나오면 만점, 조금만 바뀌면 0점.
//
// [원인]
//   - 모델이 너무 복잡 (파라미터가 데이터에 비해 과하게 많음)
//   - 데이터가 너무 적음
//   - 너무 오래 학습
//
// [신호]
//   훈련 손실은 계속 낮아지는데, 검증 손실은 어느 순간부터 올라간다.
//   -> 이 지점이 "외우기 시작한" 순간.
 
fn concept6_overfitting() {
    println!("-- 개념 6: 과적합 vs 일반화 --\n");
 
    println!("학습의 목표 = 훈련 데이터 '암기'가 아니라");
    println!("             새 데이터에도 맞추기 = '일반화'\n");
 
    println!("비유: 시험 공부");
    println!("  . 일반화 잘 됨 = 원리를 이해 -> 새 문제도 풀어냄");
    println!("  . 과적합       = 기출만 통째 암기 -> 변형 문제에 0점\n");
 
    let train = vec![(1.0, 2.1), (2.0, 3.9), (3.0, 6.2)]; // 대략 y=2x
    let test = vec![(4.0, 8.0), (5.0, 10.1)];             // 같은 규칙의 새 데이터
 
    let (gw, gb) = (2.0, 0.0);
    println!("올바른(일반화된) 모델  w=2, b=0:");
    println!("  훈련 손실 = {:.4}", mse(&train, gw, gb));
    println!("  테스트 손실 = {:.4}   <- 새 데이터에도 낮음 (좋음!)\n", mse(&test, gw, gb));
 
    println!("과적합 모델의 전형적 증상:");
    println!("  훈련 손실 -> 0 에 가깝게 계속 내려감");
    println!("  테스트 손실 -> 어느 순간부터 다시 올라감 (외우기 시작)");
    println!();
 
    println!("학습 곡선 모양 (단계가 진행될수록):");
    println!("  훈련 손실:   높음 --------> 계속 낮아짐");
    println!("  검증 손실:   높음 --> 낮아짐 --> (!) 다시 올라감");
    println!("                            ^");
    println!("                      여기서 멈춰야 함 (조기 종료)\n");
 
    println!("막는 방법: 더 많은 데이터, 단순한 모델, 조기 종료,");
    println!("           정규화(regularization), 드롭아웃 등\n");
}
 
 
// ================================================================
// 개념 7: 훈련 / 검증 / 테스트 세트 분리
// ================================================================
//
// 과적합을 '탐지'하려면 모델이 본 적 없는 데이터로 평가해야 한다.
// 그래서 데이터를 세 덩어리로 나눈다.
//
//   훈련 세트 (Train, ~70%):
//      모델이 학습에 사용. 가중치가 이 데이터로 조정된다.
//
//   검증 세트 (Validation, ~15%):
//      학습 중간중간 성능 점검 + 설정(학습률 등) 튜닝용.
//      "언제 멈출지", "어떤 모델이 나은지" 결정.
//
//   테스트 세트 (Test, ~15%):
//      학습이 다 끝난 뒤 '딱 한 번' 쓰는 최종 시험.
//      절대 학습이나 튜닝에 쓰면 안 된다 (정직한 성적표).
//
// 왜 나누나?
//   훈련 데이터로 평가하면 "외운 걸 그대로 묻는" 셈이라
//   진짜 실력을 알 수 없다. 본 적 없는 데이터라야 일반화 능력이 보인다.
 
fn concept7_train_val_test() {
    println!("-- 개념 7: train / val / test 분리 --\n");
 
    println!("데이터를 셋으로 나눈다:");
    println!("  훈련(Train, ~70%):      가중치 학습에 사용");
    println!("  검증(Validation, ~15%): 학습 중 점검 + 설정 튜닝, 멈출 시점 결정");
    println!("  테스트(Test, ~15%):     끝난 뒤 단 한 번, 최종 성적표");
    println!();
 
    let all: Vec<i32> = (1..=10).collect();
    let train = &all[0..7];
    let val = &all[7..9];
    let test = &all[9..10];
    println!("예시: 데이터 10개 분리");
    println!("  훈련  = {:?}", train);
    println!("  검증  = {:?}", val);
    println!("  테스트 = {:?}", test);
    println!();
 
    println!("왜 나누나?");
    println!("  훈련 데이터로 평가 = 외운 걸 그대로 묻기 -> 실력 과대평가");
    println!("  본 적 없는 데이터로 평가해야 '진짜 일반화 능력'이 보인다");
    println!();
    println!("철칙: 테스트 세트는 학습/튜닝에 절대 쓰지 않는다");
    println!("      (한 번이라도 보면 더 이상 '공정한 시험'이 아님)\n");
}
 
 
