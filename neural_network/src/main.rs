// ================================================================
// Part 1: 퍼셉트론 (뉴런 1개)
// ================================================================
//
// 신경망의 최소 단위 = 뉴런(퍼셉트론).
// 하는 일은 딱 두 단계:
//   1) 입력들에 가중치를 곱해 모두 더하고 편향을 더한다 (가중합)
//        z = w1*x1 + w2*x2 + ... + b
//   2) 그 결과를 활성화 함수에 통과시킨다
//        output = activation(z)
//
// '가중합'은 입력 벡터와 가중치 벡터의 내적(dot product)이다.
 
fn part1_perceptron() {
    println!("-- Part 1: 퍼셉트론 (뉴런 1개) --\n");
 
    let x = [1.0, 2.0, 3.0];      // 입력 3개
    let w = [0.5, -0.3, 0.8];     // 가중치 3개
    let b = 0.1;                  // 편향
 
    // 1) 가중합 z = w·x + b
    let z: f64 = x.iter().zip(w.iter()).map(|(xi, wi)| xi * wi).sum::<f64>() + b;
 
    // 2) 활성화 (여기선 ReLU)
    let out = relu(z);
 
    println!("입력 x = {:?}", x);
    println!("가중치 w = {:?}, 편향 b = {b}", w);
    println!("가중합 z = w·x + b = ({:.1})+({:.1})+({:.1})+{b} = {z:.2}",
        x[0]*w[0], x[1]*w[1], x[2]*w[2]);
    println!("출력 = ReLU({z:.2}) = {out:.2}");
    println!();
    println!("-> 뉴런 = 가중합 후 활성화. 이게 신경망의 최소 단위.\n");
}

// ================================================================
// 활성화 함수 구현
// ================================================================
 
/// ReLU(x) = max(0, x)
fn relu(x: f64) -> f64 {
    if x > 0.0 { x } else { 0.0 }
}
 
/// Sigmoid(x) = 1 / (1 + e^-x)
fn sigmoid(x: f64) -> f64 {
    1.0 / (1.0 + (-x).exp())
}
 
/// GELU(x) = 0.5x(1 + tanh(√(2/π)(x + 0.044715x³)))  (tanh 근사식)
fn gelu(x: f64) -> f64 {
    let c = (2.0 / std::f64::consts::PI).sqrt();
    0.5 * x * (1.0 + (c * (x + 0.044715 * x.powi(3))).tanh())
}
 
 
// ================================================================
// 레이어 (행렬 곱 + 편향)
// ================================================================
 
/// 선형 레이어: output = W @ input + b
///   W: (출력 x 입력) 행렬, input: 입력 벡터, b: 편향 벡터
fn linear(w: &[Vec<f64>], b: &[f64], input: &[f64]) -> Vec<f64> {
    w.iter()
        .zip(b.iter())
        .map(|(row, &bias)| {
            // 한 뉴런의 출력 = (가중치 행 · 입력) + 편향
            let dot: f64 = row.iter().zip(input.iter()).map(|(wi, xi)| wi * xi).sum();
            dot + bias
        })
        .collect()
}
 
 
// ================================================================
// ASCII 그래프 (활성화 함수 모양 보기)
// ================================================================
// x를 -4~4로 훑으며 함수값을 가로 위치로 찍는다. (세로축 = x, 가로축 = 값)
 
fn plot_activation(name: &str, f: fn(f64) -> f64) {
    println!("[{name}] 모양 (세로=x, 가로=출력, | 는 출력=0 기준선):");
    let width = 40;
    // 출력 범위 추정 (-4~4 입력에 대해)
    let mut x = 4.0;
    while x >= -4.0 {
        let y = f(x);
        // y를 -1~4 범위로 보고 가로 위치 계산 (0 기준선 포함)
        let zero_col = 8; // 출력 0의 가로 위치
        let scale = 7.0;  // 한 칸당 출력 폭
        let col = (zero_col as f64 + y * scale).round() as i64;
        let col = col.clamp(0, width as i64) as usize;
 
        let mut line = vec![' '; width + 1];
        if zero_col <= width { line[zero_col] = '|'; } // 0 기준선
        if col <= width { line[col] = '*'; }
        let s: String = line.into_iter().collect();
        println!("x={x:>4.1} {s}");
        x -= 1.0;
    }
    println!();
}