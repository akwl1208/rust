// ================================================================
// Part 1: 퍼셉트론 (뉴런 1개)
// ================================================================
//
// 신경망의 최소 단위 = 뉴런(퍼셉트론).
// 하는 일은 딱 두 단계:
//   1) 입력들에 가중치를 곱해 모두 더하고 편향을 더한다 (가중합)
//        z = w1*x1 + w2*x2 + ... + b
//   2) 그 결과를 활성화 함수에 통과시킨다
//        output = activation(z)
//
// '가중합'은 입력 벡터와 가중치 벡터의 내적(dot product)이다.
 
fn part1_perceptron() {
    println!("-- Part 1: 퍼셉트론 (뉴런 1개) --\n");
 
    let x = [1.0, 2.0, 3.0];      // 입력 3개
    let w = [0.5, -0.3, 0.8];     // 가중치 3개
    let b = 0.1;                  // 편향
 
    // 1) 가중합 z = w·x + b
    let z: f64 = x.iter().zip(w.iter()).map(|(xi, wi)| xi * wi).sum::<f64>() + b;
 
    // 2) 활성화 (여기선 ReLU)
    let out = relu(z);
 
    println!("입력 x = {:?}", x);
    println!("가중치 w = {:?}, 편향 b = {b}", w);
    println!("가중합 z = w·x + b = ({:.1})+({:.1})+({:.1})+{b} = {z:.2}",
        x[0]*w[0], x[1]*w[1], x[2]*w[2]);
    println!("출력 = ReLU({z:.2}) = {out:.2}");
    println!();
    println!("-> 뉴런 = 가중합 후 활성화. 이게 신경망의 최소 단위.\n");
}

// ================================================================
// Part 2: 활성화 함수
// ================================================================
//
// 활성화 함수가 '왜' 필요한가?
//   활성화가 없으면 신경망은 아무리 층을 쌓아도 결국 '직선(선형)'
//   하나로 합쳐진다. 비선형 활성화가 있어야 곡선/복잡한 패턴을
//   학습할 수 있다. (층을 쌓는 의미가 생긴다)
//
// 주요 함수:
//   ReLU(x)    = max(0, x)
//      음수는 0, 양수는 그대로. 단순하고 빠름. 딥러닝의 기본.
//
//   Sigmoid(x) = 1 / (1 + e^-x)
//      모든 값을 0~1 사이로 눌러줌. 확률처럼 해석 가능.
//      단점: 값이 크면 기울기가 0에 가까워짐(기울기 소실).
//
//   GELU(x)    = 0.5x(1 + tanh(√(2/π)(x + 0.044715x³)))
//      ReLU의 '부드러운' 버전. 0 근처에서 매끄럽게 꺾임.
//      GPT, BERT 등 Transformer가 주로 사용.
 
fn part2_activations() {
    println!("-- Part 2: 활성화 함수 (ReLU, Sigmoid, GELU) --\n");
 
    println!("활성화가 필요한 이유: 비선형성을 주어 복잡한 패턴 학습 가능\n");
 
    // 값 비교표
    println!("{:>6} {:>8} {:>10} {:>10}", "x", "ReLU", "Sigmoid", "GELU");
    println!("{}", "-".repeat(38));
    for x in [-3.0, -1.0, -0.5, 0.0, 0.5, 1.0, 3.0] {
        println!("{x:>6.1} {:>8.3} {:>10.4} {:>10.4}", relu(x), sigmoid(x), gelu(x));
    }
    println!();
 
    // ASCII 그래프로 모양 보기
    plot_activation("ReLU", relu);
    plot_activation("Sigmoid", sigmoid);
    plot_activation("GELU", gelu);
}

// ================================================================
// Part 3: 레이어 (뉴런들의 집합 = 행렬 곱)
// ================================================================
//
// 뉴런 하나가 아니라 여러 개를 한 줄로 세운 것이 '레이어'.
// 뉴런 4개짜리 레이어 = 가중치 벡터 4개 = 가중치 '행렬'.
//
//   레이어 출력 = W @ input + b
//     W: (출력뉴런수 x 입력수) 행렬
//     input: 입력 벡터
//     b: 편향 벡터 (출력뉴런 수만큼)
//
// 즉 레이어 = 행렬 곱 한 번 + 편향 더하기 + 활성화.
// 신경망의 순전파가 '거대한 행렬 곱의 연속'인 이유가 이것.
 
fn part3_layer() {
    println!("-- Part 3: 레이어 (뉴런들의 집합 = 행렬 곱) --\n");
 
    let x = vec![1.0, 2.0, 3.0];  // 입력 3개
 
    // 출력 뉴런 2개짜리 레이어: W는 2x3 행렬
    let w = vec![
        vec![0.5, -0.3, 0.8],   // 1번 뉴런의 가중치
        vec![-0.2, 0.4, 0.1],   // 2번 뉴런의 가중치
    ];
    let b = vec![0.1, -0.1];
 
    let z = linear(&w, &b, &x); // W@x + b
 
    println!("입력 x = {:?} (3개)", x);
    println!("레이어: 뉴런 2개 -> W는 2x3 행렬");
    println!("출력 z = W@x + b = {:?}",
        z.iter().map(|v| format!("{v:.2}")).collect::<Vec<_>>());
    println!();
    println!("-> 뉴런 N개 레이어 = 행렬 곱 한 번. 활성화는 그 다음 단계.\n");
}

// ================================================================
// 활성화 함수 구현
// ================================================================
 
/// ReLU(x) = max(0, x)
fn relu(x: f64) -> f64 {
    if x > 0.0 { x } else { 0.0 }
}
 
/// Sigmoid(x) = 1 / (1 + e^-x)
fn sigmoid(x: f64) -> f64 {
    1.0 / (1.0 + (-x).exp())
}
 
/// GELU(x) = 0.5x(1 + tanh(√(2/π)(x + 0.044715x³)))  (tanh 근사식)
fn gelu(x: f64) -> f64 {
    let c = (2.0 / std::f64::consts::PI).sqrt();
    0.5 * x * (1.0 + (c * (x + 0.044715 * x.powi(3))).tanh())
}
 
 
// ================================================================
// 레이어 (행렬 곱 + 편향)
// ================================================================
 
/// 선형 레이어: output = W @ input + b
///   W: (출력 x 입력) 행렬, input: 입력 벡터, b: 편향 벡터
fn linear(w: &[Vec<f64>], b: &[f64], input: &[f64]) -> Vec<f64> {
    w.iter()
        .zip(b.iter())
        .map(|(row, &bias)| {
            // 한 뉴런의 출력 = (가중치 행 · 입력) + 편향
            let dot: f64 = row.iter().zip(input.iter()).map(|(wi, xi)| wi * xi).sum();
            dot + bias
        })
        .collect()
}
 
 
// ================================================================
// ASCII 그래프 (활성화 함수 모양 보기)
// ================================================================
// x를 -4~4로 훑으며 함수값을 가로 위치로 찍는다. (세로축 = x, 가로축 = 값)
 
fn plot_activation(name: &str, f: fn(f64) -> f64) {
    println!("[{name}] 모양 (세로=x, 가로=출력, | 는 출력=0 기준선):");
    let width = 40;
    // 출력 범위 추정 (-4~4 입력에 대해)
    let mut x = 4.0;
    while x >= -4.0 {
        let y = f(x);
        // y를 -1~4 범위로 보고 가로 위치 계산 (0 기준선 포함)
        let zero_col = 8; // 출력 0의 가로 위치
        let scale = 7.0;  // 한 칸당 출력 폭
        let col = (zero_col as f64 + y * scale).round() as i64;
        let col = col.clamp(0, width as i64) as usize;
 
        let mut line = vec![' '; width + 1];
        if zero_col <= width { line[zero_col] = '|'; } // 0 기준선
        if col <= width { line[col] = '*'; }
        let s: String = line.into_iter().collect();
        println!("x={x:>4.1} {s}");
        x -= 1.0;
    }
    println!();
}